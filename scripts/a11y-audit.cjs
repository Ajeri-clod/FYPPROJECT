/**
 * Accessibility audit (WCAG 2.1 A/AA + best practice) with axe-core.
 *
 *   1. start the dashboard:   bun run dev
 *   2. in another terminal:   bun run a11y
 *
 * Signs in with the dev account, checks every page in light and dark mode,
 * and writes docs/evaluation/accessibility-audit.md.
 */
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");

const BASE = process.env.BASE_URL ?? "http://localhost:3000";
const PAGES = [
  "/login",
  "/",
  "/profiles",
  "/employment",
  "/placements",
  "/labour-market",
  "/jobs",
  "/recommendations",
  "/skill-gap",
  "/settings",
];
const AXE = fs.readFileSync(require.resolve("axe-core/axe.min.js"), "utf8");
const TAGS = ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "best-practice"];

(async () => {
  const browser = await chromium.launch();
  const rows = [];
  for (const scheme of ["light", "dark"]) {
    const ctx = await browser.newContext({
      colorScheme: scheme,
      reducedMotion: "reduce",
      viewport: { width: 1440, height: 1000 },
    });
    const page = await ctx.newPage();
    for (const url of PAGES) {
      await page.goto(BASE + url);
      await page.waitForLoadState("networkidle");
      if (url !== "/login" && page.url().includes("/login")) {
        await page.getByText("Dev quick login").click();
        await page.waitForURL(`${BASE}/`);
        await page.goto(BASE + url);
        await page.waitForLoadState("networkidle");
      }
      await page.waitForTimeout(1000);
      await page.addScriptTag({ content: AXE });
      const result = await page.evaluate(
        (tags) =>
          window.axe.run(document, { runOnly: { type: "tag", values: tags } }),
        TAGS,
      );
      rows.push({
        scheme,
        url,
        passes: result.passes.length,
        violations: result.violations.map(
          (v) => `${v.id} (${v.impact}, ${v.nodes.length})`,
        ),
      });
    }
    await ctx.close();
  }
  await browser.close();

  const total = rows.reduce((n, r) => n + r.violations.length, 0);
  const md = [
    "# Accessibility audit",
    "",
    `Generated by \`bun run a11y\` on ${new Date().toISOString().slice(0, 10)} with axe-core ${require("axe-core/package.json").version}.`,
    `Standard: WCAG 2.1 Level A and AA, plus axe best-practice rules. Pages: ${PAGES.length}, each in light and dark mode.`,
    "",
    `**Result: ${total === 0 ? "no violations" : `${total} violation type(s) found`}.**`,
    "",
    "| Theme | Page | Rules passed | Violations |",
    "|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| ${r.scheme} | \`${r.url}\` | ${r.passes} | ${r.violations.length ? r.violations.join("; ") : "none"} |`,
    ),
    "",
    "Automated checks find roughly a third to a half of accessibility problems.",
    "Manual checks done as well: keyboard-only navigation (skip link, visible focus),",
    "reduced-motion setting, and 44px touch targets on touch screens.",
    "Not yet done: testing with screen-reader users and OKU participants.",
    "",
  ].join("\n");
  fs.mkdirSync(path.join(process.cwd(), "docs", "evaluation"), {
    recursive: true,
  });
  fs.writeFileSync(
    path.join(process.cwd(), "docs", "evaluation", "accessibility-audit.md"),
    md,
  );
  console.log(
    total === 0
      ? "No violations."
      : `${total} violation type(s) — see docs/evaluation/accessibility-audit.md`,
  );
  process.exit(total === 0 ? 0 : 1);
})();

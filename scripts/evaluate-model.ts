/**
 * Evaluate the job recommender on the benchmark and write a report.
 *
 *   bun run evaluate-model
 *
 * Writes docs/evaluation/model-evaluation.md (tables ready for Chapter 4) and
 * src/data/model-evaluation.json (shown on the Job Recommendations page).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { demoJobs } from "../src/features/jobs/demo-data";
import { sampleCandidates } from "../src/features/matching/candidates";
import {
  CANDIDATE_FAMILIES,
  evaluateRecommender,
} from "../src/features/matching/evaluation";

const K = 5;
const r = evaluateRecommender(demoJobs, sampleCandidates, K);
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

const summary = {
  k: K,
  benchmark:
    "30 sample Selangor job postings (27 open) × 16 sample job-seekers",
  evaluatedOn: new Date().toISOString().slice(0, 10),
  precisionAtK: r.meanPrecisionAtK,
  bestPossiblePrecisionAtK: r.meanBestPossiblePrecision,
  rPrecisionAtK: r.meanRPrecisionAtK,
  hitRateAt1: r.hitRateAt1,
  meanReciprocalRank: r.meanReciprocalRank,
  randomPrecisionAtK: r.meanRandomPrecision,
  candidatesEvaluated: r.candidatesEvaluated,
  candidatesSkipped: r.candidatesSkipped,
};
writeFileSync(
  join(process.cwd(), "src", "data", "model-evaluation.json"),
  `${JSON.stringify(summary, null, 1)}\n`,
);

const rows = r.perCandidate
  .map(
    (c) =>
      `| ${c.candidateId} | ${(CANDIDATE_FAMILIES[c.candidateId] ?? []).join(", ")} | ${c.relevantOpen} | ${pct(c.precisionAtK)} | ${pct(c.bestPossiblePrecision)} | ${pct(c.rPrecisionAtK)} | ${c.hitAt1 ? "Yes" : "No"} | ${c.reciprocalRank.toFixed(2)} | ${c.top.map((t) => `${t.relevant ? "✓" : "✗"} ${t.title} (${t.score.toFixed(2)})`).join("; ")} |`,
  )
  .join("\n");

const md = `# Job recommender evaluation (Precision@${K})

Generated by \`bun run evaluate-model\` on ${summary.evaluatedOn}.

## Method

- **Model:** Content-Based Filtering. TF-IDF vectors of the job-seeker's skills,
  education and experience vs the job's skills, title and description,
  ranked by cosine similarity.
- **Benchmark:** ${summary.benchmark}. Closed postings are excluded, as on the dashboard.
- **Ground truth (defined independently of the model):** every job has an
  occupation family, and every job-seeker has the families that suit their
  background (see \`src/features/matching/evaluation.ts\`). A recommended job is
  relevant when its family matches.
- **Metrics:** Precision@${K}, R-Precision@${K} (divides by min(${K}, suitable jobs)),
  Hit@1, Mean Reciprocal Rank (MRR). Baseline: random selection.

## Results

| Metric | Model | Random baseline | Best possible |
|---|---|---|---|
| Precision@${K} | **${pct(r.meanPrecisionAtK)}** | ${pct(r.meanRandomPrecision)} | ${pct(r.meanBestPossiblePrecision)} |
| R-Precision@${K} | **${pct(r.meanRPrecisionAtK)}** | | 100.0% |
| Hit@1 (top job suitable) | **${pct(r.hitRateAt1)}** | | 100.0% |
| MRR | **${r.meanReciprocalRank.toFixed(3)}** | | 1.000 |

Precision@${K} is ${(r.meanPrecisionAtK / r.meanRandomPrecision).toFixed(1)} times the random
baseline. It reaches ${pct(r.meanPrecisionAtK / r.meanBestPossiblePrecision)} of the best
possible value: many job-seekers have only one or two suitable jobs among the
${r.jobsEvaluated} open postings, which caps Precision@${K} for them regardless of
the model.

## Per job-seeker

| Job-seeker | Suitable families | Suitable open jobs | P@${K} | Best possible | R-P@${K} | Hit@1 | RR | Top ${K} (✓ suitable, cosine score) |
|---|---|---|---|---|---|---|---|---|
${rows}

## Limitations

- Job-seekers are synthetic and the benchmark is small (30 postings). The
  ground-truth labels are the researcher's judgement; a domain expert (e.g.
  MTOS or PERKESO) reviewing them would strengthen the result.
- The sample job-seekers and postings were written for this project, so their
  wording overlaps more than real profiles and adverts may.
- TF-IDF matches words, not meanings: a related skill described with different
  words is missed unless the skill vocabulary maps it.
`;
mkdirSync(join(process.cwd(), "docs", "evaluation"), { recursive: true });
writeFileSync(
  join(process.cwd(), "docs", "evaluation", "model-evaluation.md"),
  md,
);
console.log(
  `Precision@${K} ${pct(r.meanPrecisionAtK)} (random ${pct(r.meanRandomPrecision)}, best possible ${pct(r.meanBestPossiblePrecision)}), ` +
    `R-Precision ${pct(r.meanRPrecisionAtK)}, Hit@1 ${pct(r.hitRateAt1)}, MRR ${r.meanReciprocalRank.toFixed(3)}`,
);
